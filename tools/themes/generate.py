#!/usr/bin/env python3
"""Generate the Flutter built-in catalog from the daemon's canonical JSON."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IDS = ('jazz', 'space-age', 'memphis', 'y2k', 'americana', 'pixel-arcade', 'retro-desktop')


def quoted(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')


def generate():
    themes = [json.loads((ROOT / 'client-core/internal/theme/builtin' / f'{id}.json').read_text()) for id in IDS]
    lines = ['// Generated by tools/themes/generate.py; edit builtin/*.json instead.',
             "import 'package:flutter/material.dart';", "import 'theme.dart';", '', 'const styleThemes = <String, AppThemeSpec>{']
    for t in themes:
        lines += [f'  {quoted(t["id"])}: AppThemeSpec(', f'    id: {quoted(t["id"])},']
        for mode in ('light', 'dark'):
            lines += [f'    {mode}: AppPalette(']
            for role, color in t['modes'][mode].items():
                value = color[1:]
                if len(value) == 6:
                    value = 'FF' + value
                lines += [f'      {role}: Color(0x{value}),']
            lines += ['    ),']
        shape = t['shape']
        r = shape['radius']
        lines += [f'    shape: AppShape(sm: {r["sm"]}, md: {r["md"]}, lg: {r["lg"]},',
                  f'      corner: CornerStyle.{shape["corner"]}, borderWidth: {shape["borderWidth"]},',
                  f'      unit: {shape["unit"]}, shadow: ShadowStyle.{shape["shadow"]}),']
        typo = t['typography']
        fields = []
        for key in ('family', 'heading', 'mono'):
            if typo.get(key, 'system') != 'system':
                fields.append(f'{key}: {quoted(typo[key])}')
        fields.append('sizes: ' + json.dumps(typo['sizes']))
        lines += ['    typography: AppTypography(' + ', '.join(fields) + '),',
                  f'    artwork: ArtworkStyle.{t["artwork"]},',
                  f'    motion: AppMotion(style: MotionStyle.{t["motion"]}),',
                  f'    pixelIcons: {str(t["icons"] == "pixel").lower()},', '  ),']
    lines += ['};', '', 'const styleThemeNames = <String, Map<String, String>>{']
    for t in themes:
        lines += [f'  {quoted(t["id"])}: {{']
        lines += [f'    {quoted(lang)}: {quoted(name)},' for lang, name in t['name'].items()]
        lines += ['  },']
    lines += ['};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    import argparse
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    out = ROOT / 'ui/lib/style_themes.dart'
    generated = generate()
    if args.check:
        if not out.exists() or out.read_text() != generated:
            raise SystemExit('Run python3 tools/themes/generate.py to update the Flutter catalog.')
    else:
        out.write_text(generated)
