"""Generate native sharing names from the same 18-language catalog."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'client-core/cmd/pasteferry-cli/share_menu_names.json'
NAMES = json.loads(CATALOG.read_text(encoding='utf-8'))
KEY = 'Send with PasteFerry'
ARB_LOCALES = {'zh-Hans': 'zh', 'zh-Hant': 'zh_Hant_TW', 'zh-HK': 'zh_Hant_HK', 'pt-BR': 'pt'}


def interface_strings(language):
    locale = ARB_LOCALES.get(language, language)
    return json.loads((ROOT / f'ui/lib/l10n/app_{locale}.arb').read_text(encoding='utf-8'))


def service_strings(language, name):
    strings = {KEY: name, 'shareFilesOnly': interface_strings(language)['shareFilesOnly']}
    return ''.join(json.dumps(key) + ' = ' + json.dumps(value, ensure_ascii=False) + ';\n'
                   for key, value in strings.items())


def windows_header():
    lines = ['// Generated by tools/mac-services.py; edit share_menu_names.json.',
             '#pragma once', '', 'namespace share_menu_names {']
    for language, name in NAMES.items():
        identifier = language.replace('-', '_')
        lines.append(f'inline constexpr wchar_t {identifier}[] = L{json.dumps(name)};')
    return '\n'.join(lines + ['}  // namespace share_menu_names', ''])


def installer_include():
    def caption(language):
        value = interface_strings(language)['shareInstallMenu'] + ': ' + NAMES[language]
        return "'" + value.replace("'", "''") + "'"
    ids = {'ja': 0x11, 'ko': 0x12, 'ar': 0x01, 'de': 0x07, 'fr': 0x0c,
           'es': 0x0a, 'pt-BR': 0x16, 'it': 0x10, 'ru': 0x19, 'uk': 0x22,
           'pl': 0x15, 'tr': 0x1f, 'vi': 0x2a, 'id': 0x21}
    lines = ['// Generated by tools/mac-services.py from the native catalog and interface translations.',
             "function PFSharingUILanguage: Word; external 'GetUserDefaultUILanguage@kernel32.dll stdcall';",
             '', 'function ShareMenuTaskDescription(Param: String): String;',
             'var', '  Language: Word;', 'begin', '  Language := PFSharingUILanguage;',
             '  case Language and $3FF of', '    $04: begin',
             '      if (Language = $0404) or (Language = $0C04) or (Language = $1404) then',
             '        Result := ' + caption('zh-Hant'),
             '      else', '        Result := ' + caption('zh-Hans') + ';', '    end;']
    lines += [f'    ${code:02X}: Result := {caption(language)};' for language, code in ids.items()]
    lines += ['  else', '    Result := ' + caption('en') + ';', '  end;', 'end;', '']
    return '\ufeff' + '\n'.join(lines)


def write_or_check(path, content, check):
    if check:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit(f'Outdated native sharing translation: {path}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('resources', nargs='?', type=Path)
    parser.add_argument('--windows-header', type=Path)
    parser.add_argument('--installer-include', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if not args.resources and not args.windows_header and not args.installer_include:
        parser.error('provide a Resources directory, --windows-header or --installer-include')
    if args.resources:
        for language, name in NAMES.items():
            write_or_check(args.resources / f'{language}.lproj/ServicesMenu.strings',
                           service_strings(language, name), args.check)
    if args.windows_header:
        write_or_check(args.windows_header, windows_header(), args.check)
    if args.installer_include:
        write_or_check(args.installer_include, installer_include(), args.check)


if __name__ == '__main__':
    main()
