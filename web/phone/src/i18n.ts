// 香港：與台灣用字大致相同，網路、連線、QR 碼等改成香港的說法
function toHK(s: Strings): Strings {
  const fix = (v: string) =>
    v
      .replace(/網路/g, '網絡')
      .replace(/連線/g, '連接')
      .replace(/QR 碼/g, '二維碼')
      .replace(/這支/g, '這部')
      .replace(/存取/g, '訪問')
      .replace(/資料/g, '數據')
  const out: Record<string, unknown> = {}
  for (const [k, v] of Object.entries(s)) out[k] = Array.isArray(v) ? v.map(fix) : fix(v as string)
  return out as Strings
}

