export type Lang = 'zh-CN' | 'zh-TW' | 'zh-HK' | 'en' | 'ja'

function pick(langs: readonly string[]): { code: Lang; s: Strings } {
  for (const raw of langs) {
    const l = (raw || '').toLowerCase()
    if (/^zh-(hk|mo)|^zh-hant-(hk|mo)/.test(l)) return { code: 'zh-HK', s: toHK(zhTW) }
    if (/^zh-(tw|hant)/.test(l)) return { code: 'zh-TW', s: zhTW }
    if (/^zh/.test(l)) return { code: 'zh-CN', s: zh }
    if (/^ja/.test(l)) return { code: 'ja', s: ja }
    if (/^en/.test(l)) return { code: 'en', s: en }
  }
  return { code: 'en', s: en }
}

const picked = pick(navigator.languages?.length ? navigator.languages : [navigator.language])

export const lang = picked.code
export const S = picked.s

type TextKey = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings]

export function t(key: TextKey, vars?: Record<string, string | number>): string {
  let s = S[key] as string
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] === undefined ? '' : String(vars[k])))
  return s
}
